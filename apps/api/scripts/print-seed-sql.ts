// Prints the faction + alias seed as SQL, from packages/shared.
// Used once to write drizzle/0001_seed_factions.sql. Changes to the seed later go in a NEW migration;
// test/migrations.test.ts checks the database still matches the shared list.
// Run: node scripts/print-seed-sql.ts
import { FACTION_ALIAS_SEED, FACTION_SEED } from '../../../packages/shared/src/factions.ts';

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;

const factions = FACTION_SEED.map((f) => `  (${q(f.name)}, ${q(f.expansion)})`).join(',\n');
const aliases = Object.entries(FACTION_ALIAS_SEED)
  .map(([alias, name]) => `  (${q(alias)}, ${q(name)})`)
  .join(',\n');

console.log(`-- Seed: ${FACTION_SEED.length} factions and ${Object.keys(FACTION_ALIAS_SEED).length} aliases (generated by scripts/print-seed-sql.ts)
INSERT INTO "factions" ("name", "expansion") VALUES
${factions}
ON CONFLICT ("name") DO NOTHING;
--> statement-breakpoint
INSERT INTO "faction_aliases" ("alias", "faction_id")
SELECT v.alias, f.id FROM (VALUES
${aliases}
) AS v(alias, faction_name)
JOIN "factions" f ON f.name = v.faction_name
ON CONFLICT ("alias") DO NOTHING;`);
